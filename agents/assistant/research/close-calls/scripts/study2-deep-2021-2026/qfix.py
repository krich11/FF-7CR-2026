import pandas as pd,json,re
d=pd.read_pickle('players.pkl');P=json.load(open('players.json'))
n=lambda s:re.sub(r'[^a-z]','',str(s).lower().replace(' jr','').replace(' sr','').replace(' iii','').replace(' ii',''))
d['nm']=d.pid.map(lambda k:n(P.get(k,{}).get('first_name','')+P.get(k,{}).get('last_name','')))
I=pd.concat([pd.read_csv(f'inj_{s}.csv') for s in range(2021,2027)]);I=I[I.game_type=='REG'].drop_duplicates(['season','week','gsis_id'],keep='last')
I['nm']=(I.first_name.fillna('')+I.last_name.fillna('')).map(n);I['team']=I.team.replace({'LA':'LAR'})
I['q2']=(I.report_status=='Questionable').astype(int);I['lim2']=I.practice_status.fillna('').str.contains('Limited|Did Not').astype(int)
d=d.merge(I[['season','week','team','nm','q2','lim2']].drop_duplicates(['season','week','team','nm']),on=['season','week','team','nm'],how='left')
d['q']=d[['q','q2']].max(axis=1).fillna(0);d['lim']=d[['lim','lim2']].max(axis=1).fillna(0)
print(d[d.proj>=6].q.mean());d.drop(columns=['q2','lim2']).to_pickle('players.pkl')
